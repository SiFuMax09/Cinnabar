#!/usr/bin/env python3
"""Generates crates/network/src/registry_entries.rs from the output of the Minecraft data generator.

Usage: gen_registry_data.py <generated/data/minecraft dir> <registries.json> <output.rs>

The data generator is run with `java -DbundlerMainClass=net.minecraft.data.Main -jar server.jar
--reports --server`. The `data/minecraft` directory it produces and `reports/registries.json` are
the inputs.
"""
import json
import os
import sys

# Registries sent in the configuration state, in the order they are sent. Entries are sent without
# data and resolved from the client's `minecraft:core` known pack.
SYNCED = [
    "chat_type", "trim_pattern", "trim_material", "wolf_variant", "wolf_sound_variant",
    "pig_variant", "pig_sound_variant", "frog_variant", "cat_variant", "cat_sound_variant",
    "cow_sound_variant", "cow_variant", "chicken_sound_variant", "chicken_variant",
    "zombie_nautilus_variant", "painting_variant", "sulfur_cube_archetype", "damage_type",
    "banner_pattern", "enchantment", "jukebox_song", "instrument", "test_environment",
    "test_instance", "dialog", "world_clock", "timeline",
]
# The plot dimension type and biome are sent with data by the server, see `CRegistryData::all`.
CUSTOM = {
    "minecraft:dimension_type": ["minecraft:overworld"],
    "minecraft:worldgen/biome": ["cinnabar:plot", "minecraft:plains"],
}
# Registries whose entries are known to the client without being synchronized
STATIC_TAGGED = [
    "block", "item", "fluid", "entity_type", "game_event", "potion", "point_of_interest_type",
]


def list_entries(base):
    names = []
    for root, _, files in os.walk(base):
        for f in files:
            if f.endswith(".json"):
                rel = os.path.relpath(os.path.join(root, f), base)[:-5]
                names.append("minecraft:" + rel.replace(os.sep, "/"))
    return sorted(names)


def main():
    data_dir, registries_path, out_path = sys.argv[1:4]
    registries = json.load(open(registries_path))

    # registry -> list of entry names, indexed by protocol id
    ids = {}
    for name in STATIC_TAGGED:
        entries = registries["minecraft:" + name]["entries"]
        ids["minecraft:" + name] = {k: v["protocol_id"] for k, v in entries.items()}
    synced = {}
    for reg in SYNCED:
        synced["minecraft:" + reg] = list_entries(os.path.join(data_dir, reg))
    for reg, entries in list(synced.items()) + list(CUSTOM.items()):
        ids[reg] = {name: i for i, name in enumerate(entries)}

    # Tags
    tags = {}
    for registry in ids:
        reg_path = registry.split(":", 1)[1]
        base = os.path.join(data_dir, "tags", reg_path)
        if not os.path.isdir(base):
            continue
        raw = {}
        for root, _, files in os.walk(base):
            for f in files:
                if f.endswith(".json"):
                    rel = os.path.relpath(os.path.join(root, f), base)[:-5].replace(os.sep, "/")
                    raw["minecraft:" + rel] = json.load(open(os.path.join(root, f)))["values"]

        resolved = {}

        def resolve(tag, stack=()):
            if tag in resolved:
                return resolved[tag]
            result = []
            for value in raw.get(tag, []):
                value = value["id"] if isinstance(value, dict) else value
                if value.startswith("#"):
                    if value[1:] not in stack:
                        result += resolve(value[1:], stack + (tag,))
                elif value in ids[registry]:
                    result.append(ids[registry][value])
            resolved[tag] = sorted(set(result))
            return resolved[tag]

        tags[registry] = {tag: resolve(tag) for tag in sorted(raw)}

    block_entity_types = sorted(
        registries["minecraft:block_entity_type"]["entries"].items(),
        key=lambda kv: kv[1]["protocol_id"],
    )

    with open(out_path, "w") as out:
        out.write("// Generated by mc_data/gen_registry_data.py. Do not edit.\n\n")
        out.write("/// Registries synchronized in the configuration state. Every entry is sent without data;\n")
        out.write("/// the client resolves it from the `minecraft:core` known pack.\n")
        out.write("pub const SYNCED_REGISTRIES: &[(&str, &[&str])] = &[\n")
        for reg, entries in synced.items():
            out.write(f'    ("{reg}", &[\n')
            for e in entries:
                out.write(f'        "{e}",\n')
            out.write("    ]),\n")
        out.write("];\n\n")
        out.write("/// The `minecraft:block_entity_type` registry, indexed by protocol id.\n")
        out.write("pub const BLOCK_ENTITY_TYPES: &[&str] = &[\n")
        for k, _ in block_entity_types:
            out.write(f'    "{k}",\n')
        out.write("];\n\n")
        out.write("/// Tags per registry, as (tag, registry entry ids).\n")
        out.write("pub const TAGS: &[(&str, &[(&str, &[u32])])] = &[\n")
        for reg, reg_tags in tags.items():
            out.write(f'    ("{reg}", &[\n')
            for tag, values in reg_tags.items():
                out.write(f'        ("{tag}", &[{", ".join(map(str, values))}]),\n')
            out.write("    ]),\n")
        out.write("];\n")


if __name__ == "__main__":
    main()
